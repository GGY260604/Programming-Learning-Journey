/*
-------------------------------------
  Dart - Code Blocks and Semicolons
-------------------------------------

This file explains:
- What a code block is
- Why braces {} matter
- When semicolons are required
*/

void main() {

  print("Start of program");

  /*
  A code block:
  - Starts with {
  - Ends with }
  - Groups multiple statements
  */

  if (true) {
    print("Inside if block");
    print("Multiple statements allowed");
  }

  print("End of program");
}

/*
Important Rules:
- Every statement ends with ;
- Braces define scope
- Indentation improves readability but is NOT required

Same idea as C++ and Java
*/
