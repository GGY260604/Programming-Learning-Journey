/*
-------------------------------------
      Dart - bool and Comparisons
-------------------------------------

bool represents true or false.
Used heavily in:
- conditions
- UI state
- visibility logic
*/

void main() {
  bool isLoggedIn = true;
  bool hasError = false;

  print(isLoggedIn);
  print(hasError);

  print(10 > 5);
  print(3 == 4);
}

/*
Rules:
- bool is lowercase
- Result of comparisons is always bool

Flutter usage:
- if (isLoading)
- if (isDarkMode)
*/
