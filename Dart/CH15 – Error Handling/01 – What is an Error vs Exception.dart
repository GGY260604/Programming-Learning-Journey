IMPORTANT CONCEPT (do not skip):

An ERROR:
- usually indicates a programming bug
- often unrecoverable
- example: out-of-memory, stack overflow

An EXCEPTION:
- represents something unexpected but recoverable
- example: invalid input, file not found, parse failure

In Dart:
- Both are objects
- Both can be thrown
- We usually HANDLE exceptions, not errors
