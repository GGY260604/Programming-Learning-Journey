/*
-------------------------------------
          Dart - if else
-------------------------------------

Used to execute code based on conditions.
*/

void main() {
  int age = 20;

  if (age >= 18) {
    print("Adult");
  } else {
    print("Minor");
  }
}

/*
Rules:
- Condition must be bool
- Curly braces define blocks
- else is optional

Flutter usage:
- login checks
- permission logic
*/
