/*
-------------------------------------
       Dart - for loop
-------------------------------------

Used when number of iterations is known.
*/

void main() {
  for (int i = 0; i < 5; i++) {
    print("i = $i");
  }
}

/*
Output:
i = 0
i = 1
i = 2
i = 3
i = 4

Flutter usage:
- building widget lists
- iteration over indexes
*/
