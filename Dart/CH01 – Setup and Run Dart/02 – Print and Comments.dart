/*
-------------------------------------
      Dart - Print and Comments
-------------------------------------
This file demonstrates:
- Single-line comments
- Multi-line comments
- print() behavior
*/

void main() {
  // This is a single-line comment

  /*
    This is a multi-line comment
    Used for long explanations
  */

  print("Line 1");
  print("Line 2");
  print("Line 3");
}

/*
Output:
Line 1
Line 2
Line 3

Note:
- print() automatically adds a newline
- Dart does NOT have cout or System.out
- print() is mainly for debugging and logging
*/
