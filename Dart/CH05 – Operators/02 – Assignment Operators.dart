/*
-------------------------------------
      Dart - Assignment Operators
-------------------------------------

Used to assign or update values.
*/

void main() {
  int x = 10;

  x += 5; // x = x + 5
  print(x);

  x -= 3; // x = x - 3
  print(x);

  x *= 2; // x = x * 2
  print(x);

  x ~/= 4; // integer division assignment
  print(x);
}

