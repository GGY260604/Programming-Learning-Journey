# ------------------------------------------------------------
# WHAT IS A LOOP?
# ------------------------------------------------------------
# A loop allows you to repeat code multiple times
#
# Instead of writing:
# print("Hello")
# print("Hello")
# print("Hello")
#
# You can use a loop
# ------------------------------------------------------------


# ------------------------------------------------------------
# BASIC FOR LOOP
# ------------------------------------------------------------
# Syntax:
#
# for variable in sequence:
#     code to run
# ------------------------------------------------------------

for i in range(5):
    print("Hello")


# ------------------------------------------------------------
# HOW RANGE() WORKS
# ------------------------------------------------------------
# range(n) → generates numbers from 0 to n-1

for i in range(5):
    print(i)   # 0,1,2,3,4


# ------------------------------------------------------------
# RANGE WITH START AND END
# ------------------------------------------------------------

for i in range(1, 6):
    print(i)   # 1 to 5


# ------------------------------------------------------------
# RANGE WITH STEP
# ------------------------------------------------------------

for i in range(0, 10, 2):
    print(i)   # 0,2,4,6,8


# ------------------------------------------------------------
# USING LOOP VARIABLE
# ------------------------------------------------------------

for i in range(5):
    print("Iteration:", i)


# ------------------------------------------------------------
# LOOP WITH INPUT
# ------------------------------------------------------------

n = int(input("How many times to repeat? "))

for i in range(n):
    print("Repeat", i + 1)


# ------------------------------------------------------------
# LOOP THROUGH STRING
# ------------------------------------------------------------

name = "Galen"

for char in name:
    print(char)


# ------------------------------------------------------------
# LOOP THROUGH LIST (Preview)
# ------------------------------------------------------------

numbers = [10, 20, 30]

for num in numbers:
    print(num)


# ------------------------------------------------------------
# COMMON BEGINNER MISTAKES
# ------------------------------------------------------------

# ❌ Forget colon :
# for i in range(5)

# ❌ Wrong indentation
# for i in range(5):
# print(i)

# ❌ Confusing range end value
