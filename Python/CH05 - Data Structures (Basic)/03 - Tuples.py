# ------------------------------------------------------------
# WHAT IS A TUPLE?
# ------------------------------------------------------------
# A tuple is similar to a list, BUT:
#
# - ordered
# - allows duplicates
# - IMMUTABLE (cannot be changed)
#
# Tuple uses ( ) instead of [ ]
# ------------------------------------------------------------


# ------------------------------------------------------------
# CREATING A TUPLE
# ------------------------------------------------------------

numbers = (10, 20, 30, 40)
print(numbers)

names = ("Alice", "Bob", "Charlie")
print(names)


# ------------------------------------------------------------
# ACCESSING ELEMENTS
# ------------------------------------------------------------
# Same as list (indexing)

print(numbers[0])   # 10
print(numbers[-1])  # 40


# ------------------------------------------------------------
# IMMUTABLE (IMPORTANT)
# ------------------------------------------------------------
# You CANNOT change tuple values

# ❌ This will cause error:
# numbers[1] = 99


# ------------------------------------------------------------
# TUPLE LENGTH
# ------------------------------------------------------------

print(len(numbers))


# ------------------------------------------------------------
# LOOP THROUGH TUPLE
# ------------------------------------------------------------

for num in numbers:
    print(num)


# ------------------------------------------------------------
# SINGLE ELEMENT TUPLE (IMPORTANT)
# ------------------------------------------------------------
# Must include comma

t = (5,)   # correct
print(type(t))

# ❌ Wrong:
# t = (5)   # this is just an integer


# ------------------------------------------------------------
# MIXED DATA TYPES
# ------------------------------------------------------------

mixed = (1, "Hello", 3.5)
print(mixed)


# ------------------------------------------------------------
# COUNT AND INDEX
# ------------------------------------------------------------

nums = (1, 2, 2, 3)

print(nums.count(2))   # 2
print(nums.index(3))   # 3


# ------------------------------------------------------------
# CONVERT BETWEEN LIST AND TUPLE
# ------------------------------------------------------------

my_list = [1, 2, 3]

# list → tuple
my_tuple = tuple(my_list)
print(my_tuple)

# tuple → list
new_list = list(my_tuple)
print(new_list)


# ------------------------------------------------------------
# WHEN TO USE TUPLE?
# ------------------------------------------------------------
# Use tuple when:
# - data should NOT change
# - fixed values (e.g., coordinates, config)
#
# Example:
point = (10, 20)


# ------------------------------------------------------------
# COMMON BEGINNER MISTAKES
# ------------------------------------------------------------

# ❌ Trying to modify tuple

# ❌ Forget comma in single-element tuple

# ❌ Confusing list [] and tuple ()


# ------------------------------------------------------------
# DEBUG TIP
# ------------------------------------------------------------

data = (1, 2, 3)
print("DEBUG:", data, type(data))


