# ------------------------------------------------------------
# FILE PATH OPERATIONS
# ------------------------------------------------------------

path = "folder/file.txt"

print("File name:", os.path.basename(path))
print("Folder path:", os.path.dirname(path))


# ------------------------------------------------------------
# JOIN PATH (IMPORTANT)
# ------------------------------------------------------------

folder = "data"
file = "info.txt"

full_path = os.path.join(folder, file)

print("Full path:", full_path)


