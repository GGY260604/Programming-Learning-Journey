# ------------------------------------------------------------
# IMPORT OS
# ------------------------------------------------------------

import os


# ------------------------------------------------------------
# CURRENT DIRECTORY
# ------------------------------------------------------------

print("Current directory:", os.getcwd())


# ------------------------------------------------------------
# LIST FILES IN DIRECTORY
# ------------------------------------------------------------

files = os.listdir()

print("Files and folders:", files)


