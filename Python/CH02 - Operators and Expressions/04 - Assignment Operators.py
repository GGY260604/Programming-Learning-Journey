# ------------------------------------------------------------
# WHAT ARE ASSIGNMENT OPERATORS?
# ------------------------------------------------------------
# Assignment operators are used to assign values to variables
#
# Basic:
# =
#
# Advanced (shortcut):
# +=, -=, *=, /=, etc
# ------------------------------------------------------------


# ------------------------------------------------------------
# BASIC ASSIGNMENT (=)
# ------------------------------------------------------------

x = 10
print("x =", x)


# ------------------------------------------------------------
# ADD AND ASSIGN (+=)
# ------------------------------------------------------------
# Same as: x = x + value

x = 10
x += 5   # x = x + 5

print("x += 5 →", x)   # 15


# ------------------------------------------------------------
# SUBTRACT AND ASSIGN (-=)
# ------------------------------------------------------------

x = 10
x -= 3   # x = x - 3

print("x -= 3 →", x)   # 7


# ------------------------------------------------------------
# MULTIPLY AND ASSIGN (*=)
# ------------------------------------------------------------

x = 10
x *= 2   # x = x * 2

print("x *= 2 →", x)   # 20


# ------------------------------------------------------------
# DIVIDE AND ASSIGN (/=)
# ------------------------------------------------------------

x = 10
x /= 2   # x = x / 2

print("x /= 2 →", x)   # 5.0


# ------------------------------------------------------------
# FLOOR DIVIDE AND ASSIGN (//=)
# ------------------------------------------------------------

x = 10
x //= 3   # x = x // 3

print("x //= 3 →", x)   # 3


# ------------------------------------------------------------
# MODULUS AND ASSIGN (%=)
# ------------------------------------------------------------

x = 10
x %= 3   # x = x % 3

print("x %= 3 →", x)   # 1


# ------------------------------------------------------------
# EXPONENT AND ASSIGN (**=)
# ------------------------------------------------------------

x = 2
x **= 3   # x = x ** 3

print("x **= 3 →", x)   # 8


# ------------------------------------------------------------
# REAL EXAMPLE (VERY USEFUL)
# ------------------------------------------------------------
# Imagine tracking score

score = 0

score += 10   # player gains points
score += 5
score -= 3    # penalty

print("Final score:", score)


# ------------------------------------------------------------
# USING WITH INPUT
# ------------------------------------------------------------

balance = 100

deposit = int(input("Enter deposit amount: "))
balance += deposit

print("New balance:", balance)


# ------------------------------------------------------------
# COMMON BEGINNER MISTAKES
# ------------------------------------------------------------

# ❌ Forget variable exists
# x += 5   <-- ERROR if x not defined

# ❌ Confusing = and ==
# =  → assignment
# == → comparison


