# ------------------------------------------------------------
# WHAT IS OPERATOR PRECEDENCE?
# ------------------------------------------------------------
# Operator precedence determines the ORDER in which
# operations are performed in an expression
#
# Example:
# 2 + 3 * 4  ≠ (2 + 3) * 4
# ------------------------------------------------------------


# ------------------------------------------------------------
# BASIC EXAMPLE
# ------------------------------------------------------------

result = 2 + 3 * 4
print("2 + 3 * 4 =", result)   # 14 (not 20)

# Why?
# Multiplication (*) runs BEFORE addition (+)


# ------------------------------------------------------------
# USING PARENTHESES ()
# ------------------------------------------------------------
# Parentheses override precedence

result = (2 + 3) * 4
print("(2 + 3) * 4 =", result)   # 20


# ------------------------------------------------------------
# ORDER OF OPERATIONS (IMPORTANT)
# ------------------------------------------------------------
# From highest → lowest:
#
# 1. ()      → Parentheses
# 2. **      → Exponent
# 3. *, /, //, %
# 4. +, -
# 5. Comparison operators (==, >, <, etc)
# 6. Logical operators (and, or, not)
# ------------------------------------------------------------


# ------------------------------------------------------------
# MORE EXAMPLES
# ------------------------------------------------------------

print(10 + 2 * 5)       # 20
print((10 + 2) * 5)     # 60

print(2 ** 3 * 2)       # 16 (2^3 = 8 → 8 * 2)
print(2 ** (3 * 2))     # 64


# ------------------------------------------------------------
# COMBINED WITH COMPARISON
# ------------------------------------------------------------

result = 5 + 5 > 8
print("5 + 5 > 8 =", result)   # True


# ------------------------------------------------------------
# COMBINED WITH LOGICAL
# ------------------------------------------------------------

result = 10 > 5 and 3 < 1
print("Logical result:", result)   # False


# ------------------------------------------------------------
# COMMON BEGINNER MISTAKES
# ------------------------------------------------------------

# ❌ Assuming left-to-right always
# 2 + 3 * 4   # WRONG expectation: 20

# ❌ Not using parentheses → confusing code

# Bad:
result = 10 + 2 * 5 - 3

# Better:
result = (10 + 2) * 5 - 3


# ------------------------------------------------------------
# BEST PRACTICE
# ------------------------------------------------------------
# Always use parentheses for clarity

score = (10 + 5) * 2
print("Score:", score)


