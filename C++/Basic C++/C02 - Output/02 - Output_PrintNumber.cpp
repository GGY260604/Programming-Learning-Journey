/*
-------------------------------------
      C++ Output - Print Number
-------------------------------------
cout can also output numbers and even mix text with numbers.
*/

#include <iostream>
using namespace std;

int main() {
    int age = 20;
    cout << 10;                      // Print a number
    cout << "I am " << age << " years old."; // Combine text and variable
    return 0;
}

/*
Output:
10
I am 20 years old.

Note:
- The << operator can be used multiple times in a single statement.
- It can mix strings, numbers, and variables.
*/
