/*
-------------------------------------
     C++ Comments - Multi Line
-------------------------------------
Multi-line comments start with /* and end with *\/
They can span multiple lines.
*/

#include <iostream>
using namespace std;

int main() {
    /*
       This is a multi-line comment.
       It can describe larger code blocks,
       explain logic, or temporarily disable code.
    */
    cout << "C++ Comments are helpful!";
    return 0;
}

/*
Output:
C++ Comments are helpful!

Note:
- Multi-line comments cannot be nested.
- Use them for detailed explanations or large descriptions.
*/
