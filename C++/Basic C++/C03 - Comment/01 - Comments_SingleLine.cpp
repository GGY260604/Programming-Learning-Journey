/*
-------------------------------------
     C++ Comments - Single Line
-------------------------------------
Single-line comments start with two forward slashes //
Everything after // on the same line is ignored by the compiler.
*/

#include <iostream>
using namespace std;

int main() {
    // This is a single-line comment
    cout << "Hello World!";  // You can also place a comment after code
    return 0;
}

/*
Output:
Hello World!

Note:
- Comments are ignored by the compiler.
- Use them to explain code purpose or logic.
- Single-line comments are great for short notes or inline explanations.
*/
